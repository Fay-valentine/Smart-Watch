/**
 * @brief 基姆拉尔森公式计算周几
 * @param y 年
 * @param m 月
 * @param d 日
 * @param c 世纪
 * @return 1-7 对应周日到周六
 */
uint8_t weekday_calculate(int y,int m,int d,int c)
{
  int w;
  if (m == 1 || m == 2)
  {y--, m += 12;}
  w = y + y / 4 + c / 4  + 26*(m + 1)/10 + d - 1 - 2 * c;
  while(w<0)
    w+=7;
  w%=7;
  w=(w==0)?7:w;
  return w;
}

